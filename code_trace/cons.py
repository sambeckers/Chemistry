def calc_Kd(coefs:np.ndarray, T:np.ndarray, R:float = 1.987165 )->np.ndarray:
    G = coefs[0]/T + coefs[1] + coefs[2]*T + coefs[3]*T**2 + coefs[4]*T**3
    d = np.minimum(-G/(R*T), 222)
    return np.exp(d)

def solve_q(a, b, c):
    # Solves a quadratic equation: a*x^2 + b*x + c = 0
    discriminant = b**2 - 4*a*c
    if np.any(discriminant < 0):
        raise ValueError("No real roots.")
    return (-b + np.sqrt(discriminant)) / (2*a)
